# Funzione per effettuare il padding delle frasi
def encode_sentence(sentence, vocab, max_length=20):
 tokens = [vocab.get(token, vocab["<UNK>"]) for token in sentence]
 # Esegui il padding o truncation a lunghezza fissa
 if len(tokens) < max_length:
  tokens += [vocab["<PAD>"]] * (max_length - len(tokens)) # Padding
 else:
  tokens = tokens[:max_length] # Truncation

