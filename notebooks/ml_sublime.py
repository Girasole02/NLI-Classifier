class SNLIClassifierLightning(pl.LightningModule):
  def __init__(self, model, lr=1e-3):
    super().__init__()
    self.save_hyperparameters() #Traccia i parametri
    self.model = model
    self.lr = lr

  def forward(self, premise, hypothesis):
    return self.model(premise, hypothesis)

  def training_step(self, batch, batch_idx):
    logits = self.forward(batch["premise"], batch["hypothesis"])
    loss = F.cross_entropy(logits, batch["label"])
    preds = torch.argmax(logits, dim=1)
    acc = (preds == batch["label"]).float().mean()
    self.log("train_loss", loss, prog_bar=True)
    self.log("train_acc", acc, prog_bar=True)
    return loss

  def validation_step(self, batch, batch_idx):
    logits = self.forward(batch["premise"], batch["hypothesis"])
    loss = F.cross_entropy(logits, batch["label"])
    preds = torch.argmax(logits, dim=1)
    acc = (preds == batch["label"]).float().mean()
    self.log("val_loss", loss, prog_bar=True)
    self.log("val_acc", acc, prog_bar=True)

  def configure_optimizers(self):
    return torch.optim.Adam(self.parameters(), lr=self.lr)

